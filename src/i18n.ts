export const DICT: Record<Lang, Record<string, string>> = { en, pt, no, fr, de, es, fi, it, nl, pl, tr, ja }

// Translate a key. Falls back to English, then to `fallback`, then to the key.
// `vars` are substituted into {name} placeholders that match a provided var;
// unmatched {tokens} (e.g. money placeholders) are left untouched for loc().
export function translate(lang: Lang, key: string, fallback?: string, vars?: Record<string, string>): string {
  let s = DICT[lang]?.[key] ?? DICT.en[key] ?? fallback ?? key
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m))
  return s
}

const KEY = 'mrben.lang'

function fromLocale(): Lang {
  try {
    const langs = [navigator.language, ...(navigator.languages || [])].map(l => (l || '').toLowerCase())
    for (const l of langs) {
      if (l.startsWith('pt')) return 'pt'
      if (l.startsWith('nb') || l.startsWith('nn') || l.startsWith('no')) return 'no'
      if (l.startsWith('fr')) return 'fr'
      if (l.startsWith('de')) return 'de'
      if (l.startsWith('es')) return 'es'
      if (l.startsWith('fi')) return 'fi'
      if (l.startsWith('it')) return 'it'
      if (l.startsWith('nl')) return 'nl'
      if (l.startsWith('pl')) return 'pl'
      if (l.startsWith('tr')) return 'tr'
      if (l.startsWith('ja')) return 'ja'
      if (l.startsWith('en')) return 'en'
    }
  } catch { /* ignore */ }
  return 'en'
}

export function loadLang(): Lang {
  try {
    const saved = localStorage.getItem(KEY) as Lang | null
    if (saved && CODES.includes(saved)) return saved
  } catch { /* ignore */ }
  return fromLocale()
}

export function saveLang(l: Lang) {
  try { localStorage.setItem(KEY, l) } catch { /* ignore */ }
  try { document.documentElement.lang = l } catch { /* ignore */ }
}

export function langMeta(l: Lang): LangMeta {
  return LANGS.find(x => x.code === l) || LANGS[0]
}
